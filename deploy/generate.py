def dashboard():
    R = "15s"   # rate window: ~7 scrapes at 2 s

    def q(expr, legend):
        return {"expr": expr, "legendFormat": legend, "datasource": DS}

    def panel(pid, kind, title, targets, x, y, w, h, unit=None, desc=None, red_from=None, mappings=None,
              overrides=(), **opts):
        p = {"id": pid, "type": kind, "title": title, "datasource": DS, "gridPos": {"x": x, "y": y, "w": w, "h": h},
             "targets": [{**t, "refId": chr(65 + k)} for k, t in enumerate(targets)],
             "fieldConfig": {"defaults": {"mappings": mappings or []}, "overrides": list(overrides)}, "options": opts}
        if desc:
            p["description"] = desc
        if unit:
            p["fieldConfig"]["defaults"]["unit"] = unit
        if red_from is not None:
            p["fieldConfig"]["defaults"]["thresholds"] = {"mode": "absolute", "steps": [
                {"color": "green", "value": None}, {"color": "red", "value": red_from}]}
        return p

    gw_ok = (f'1 - ((sum(rate(http_requests_total{{service="gateway",code=~"5.."}}[{R}])) or vector(0))'
             f' / sum(rate(http_requests_total{{service="gateway"}}[{R}])))')
    panels = [
        panel(1, "stat", "Instances healthy", [q("sum(target_up)", "healthy")], 0, 0, 6, 4,
              desc="Replicas passing the monitor's readiness check (0.5 s polling)."),
        panel(2, "stat", "Instances down", [q("count(target_up) - sum(target_up)", "down")], 6, 0, 6, 4, red_from=1),
        panel(3, "stat", f"User-visible success ratio ({R})", [q(gw_ok, "success")], 12, 0, 6, 4, unit="percentunit",
              desc="Share of requests answered by the gateways without a 5xx (= measured availability)."),
        panel(4, "stat", "Writes queued in journal", [q("max(db_journal_pending) or vector(0)", "pending")], 18, 0, 6, 4,
              red_from=1, desc="Store-and-forward outbox: writes accepted with HTTP 202 while the primary DB is down."),
        panel(5, "state-timeline", "Health checks per instance (monitor, 0.5 s polling)", [q("target_up", "{{instance}}")],
              0, 4, 24, 9, showValue="never", mergeValues=True, mappings=[{"type": "value", "options": {
                  "1": {"text": "UP", "color": "green", "index": 0}, "0": {"text": "DOWN", "color": "red", "index": 1}}}]),
        panel(6, "timeseries", "Request rate by instance (req/s)",
              [q(f"sum by (instance) (rate(http_requests_total[{R}]))", "{{instance}}")], 0, 13, 12, 8, unit="reqps"),
        panel(7, "timeseries", "Failed requests (5xx/s) by instance",
              [q(f'sum(rate(http_requests_total{{code=~"5.."}}[{R}])) or vector(0)', "all instances"),
               q(f'sum by (instance) (rate(http_requests_total{{code=~"5.."}}[{R}]))', "{{instance}}")], 12, 13, 12, 8,
              unit="reqps"),
        panel(8, "timeseries", "Mean latency by instance",
              [q(f"sum by (instance) (rate(http_request_duration_seconds_sum[{R}])) / "
                 f"sum by (instance) (rate(http_request_duration_seconds_count[{R}]))", "{{instance}}")],
              0, 21, 12, 8, unit="s"),
        panel(9, "timeseries", "Faults masked by the gateway (events/s)",
              [q(f"sum(rate(gateway_{k}_total[{R}]))", label) for k, label in
               [("retries", "retry on another replica"), ("stale", "stale-cache answer (degraded)"),
                ("shed", "load shed (priority)"), ("failed", "not masked -> 503")]], 12, 21, 12, 8, unit="ops",
              desc="Retries with backoff, graceful degradation and load shedding as they happen."),
        panel(10, "timeseries", "Circuit breakers open",
              [q("(sum(gateway_circuit_open) + sum(db_circuit_open)) or vector(0)", "open breakers (total)"),
               q("sum by (target) (gateway_circuit_open) > 0", "gateway -> {{target}}"),
               q("max by (instance) (db_circuit_open) > 0", "{{instance}} -> primary DB")], 0, 29, 12, 8),
        panel(11, "timeseries", "Database: primary availability, replica failover, journal",
              [q("min(db_primary_available)", "primary available (min over services)"),
               q(f"sum(rate(db_replica_reads_total[{R}]))", "reads served by replica /s"),
               q("max(db_journal_pending)", "journal pending"),
               q(f"sum(rate(db_journal_replayed_total[{R}]))", "journal replayed /s")], 12, 29, 12, 8,
              overrides=[{"matcher": {"id": "byName", "options": "primary available (min over services)"},
                          "properties": [{"id": "custom.axisPlacement", "value": "right"}, {"id": "min", "value": 0},
                                         {"id": "max", "value": 1}, {"id": "custom.lineWidth", "value": 3}]}]),
    ]
    return {"title": "University IS - dependability", "uid": "univ-is", "schemaVersion": 39, "refresh": "5s",
            "time": {"from": "now-10m", "to": "now"}, "tags": ["fault-tolerance"], "panels": panels}


def prometheus_static(inst):
    """docker-compose: fixed container names; instance label = container name (port stripped)."""
    targets = ", ".join(f"'{i.id}:{CONTAINER_PORT}'" for i in inst)
    return PROM_GLOBAL + f"""scrape_configs:
  - job_name: university-is
    honor_labels: true            # keep the service/instance labels exported by the application
    static_configs:
      - targets: [{targets}]
    relabel_configs:
      - source_labels: [__address__]
        regex: '(([a-z]+)-[0-9]+):[0-9]+'
        replacement: '$1'
        target_label: instance
      - source_labels: [__address__]
        regex: '(([a-z]+)-[0-9]+):[0-9]+'
        replacement: '$2'
        target_label: service
  - job_name: prometheus
    static_configs:
      - targets: ['localhost:9090']
"""


def prometheus_k8s(ns):
    """Kubernetes: pods are discovered through the API (pods annotated prometheus.io/scrape=true), so replicas that
    are rescheduled or scaled are picked up automatically."""
    return PROM_GLOBAL + f"""scrape_configs:
  - job_name: university-is
    honor_labels: true
    kubernetes_sd_configs:
      - role: pod
        namespaces: {{names: [{ns}]}}
    relabel_configs:
      - source_labels: [__meta_kubernetes_pod_annotation_prometheus_io_scrape]
        regex: 'true'
        action: keep
      - source_labels: [__meta_kubernetes_pod_phase]
        regex: Running
        action: keep
      - source_labels: [__meta_kubernetes_pod_ip, __meta_kubernetes_pod_annotation_prometheus_io_port]
        regex: '(.+);(.+)'
        replacement: '$1:$2'
        target_label: __address__
      - source_labels: [__meta_kubernetes_pod_name]
        target_label: instance
      - source_labels: [__meta_kubernetes_pod_label_app]
        target_label: service
      - source_labels: [__meta_kubernetes_pod_node_name]
        target_label: k8s_node
  - job_name: prometheus
    static_configs:
      - targets: ['localhost:9090']
"""


def monitoring(inst):
    M = os.path.join(D, "monitoring")
    write(os.path.join(M, "prometheus.yml"), prometheus_static(inst))
    write(os.path.join(M, "alerts.yml"), ALERTS)
