def kind_overlay():
    """Local 3-node cluster (1 control plane + 2 workers = nodes A and B) for the Kubernetes demo."""
    K = os.path.join(D, "kind")
    mount = "    extraMounts: [{hostPath: /tmp/univ-shared, containerPath: /shared}]   # stands in for an NFS share\n"
    ports = "".join(f"      - {{containerPort: {p}, hostPort: {p}}}   # {n}\n" for n, p in NODEPORT.items())
    write(os.path.join(K, "kind-cluster.yaml"),
          "# kind create cluster --name univ --config deploy/kind/kind-cluster.yaml   (generated by deploy/generate.py)\n"
          "kind: Cluster\napiVersion: kind.x-k8s.io/v1alpha4\nnodes:\n"
          "  - role: control-plane              # also hosts monitoring, so it survives a worker failure\n"
          + mount + "    extraPortMappings:                # NodePorts reachable on localhost\n" + ports
          + "  - role: worker                     # node A\n" + mount
          + "  - role: worker                     # node B\n" + mount)
    write(os.path.join(K, "shared-pv.yaml"),
          "# ReadWriteMany volume shared by every node (same Docker-host directory mounted into all kind nodes)\n"
          "apiVersion: v1\nkind: PersistentVolume\nmetadata:\n  name: univ-shared\nspec:\n  capacity: {storage: 1Gi}\n"
          "  accessModes: [ReadWriteMany]\n  persistentVolumeReclaimPolicy: Retain\n  storageClassName: shared\n"
          "  hostPath: {path: /shared, type: DirectoryOrCreate}\n")
    pin = """      - op: add
        path: /spec/template/spec/nodeSelector
        value: {node-role.kubernetes.io/control-plane: ""}
      - op: add
        path: /spec/template/spec/tolerations
        value: [{key: node-role.kubernetes.io/control-plane, operator: Exists, effect: NoSchedule}]
"""
    write(os.path.join(K, "kustomization.yaml"),
          "# kubectl apply -k deploy/kind     (generated by deploy/generate.py)\n"
          "apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n  - ../k8s\n  - shared-pv.yaml\n"
          "patches:\n"
          "  - target: {kind: PersistentVolumeClaim, name: data}     # bind to the shared hostPath volume\n"
          "    patch: |-\n      - op: add\n        path: /spec/storageClassName\n        value: shared\n"
          "  - target: {kind: Deployment, labelSelector: tier=monitoring}   # monitoring on the control plane\n"
          "    patch: |-\n" + pin.rstrip("\n") + "\n"
          "  - target: {kind: StatefulSet, name: monitor}            # health monitor too, so it can report the failure\n"
          "    patch: |-\n" + pin)


