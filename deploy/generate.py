def k8s(inst):
    K = os.path.join(D, "k8s")
    ns = "univ"
    write(os.path.join(K, "00-namespace.yaml"), f"apiVersion: v1\nkind: Namespace\nmetadata:\n  name: {ns}\n")
    topo = {"mode": "ft", "instances": []}
    groups = {}
    for i in inst:
        if i.service == "monitor":
            groups.setdefault("monitor", []).append(i)
            continue
        groups.setdefault(i.service, []).append(i)
    # pods of a StatefulSet are <name>-0, <name>-1; the headless service gives each a stable DNS name
    for svc, items in groups.items():
        for k, i in enumerate(items):
            pod = f"{svc}-{k}"
            topo["instances"].append({"service": svc, "id": pod, "node": "A" if k == 0 else "B", "port": CONTAINER_PORT,
                                      "host": f"{pod}.{svc}"})
    cm = json.dumps(topo, indent=2).replace("\n", "\n    ")
    write(os.path.join(K, "01-config-storage.yaml"),
          f"apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: topology\n  namespace: {ns}\ndata:\n  topology.json: |\n    {cm}\n---\n"
          f"# NOTE: SQLite needs a POSIX volume shared by all pods (RWX: NFS, CephFS, Azure Files, EFS ...). No\n"
          f"# storageClassName here = the cluster default; deploy/kind/ patches in a shared hostPath volume for local\n"
          f"# clusters. For production use PostgreSQL with streaming replication instead (see report, section 11).\n"
          f"apiVersion: v1\nkind: PersistentVolumeClaim\nmetadata:\n  name: data\n  namespace: {ns}\nspec:\n  accessModes: [ReadWriteMany]\n"
          f"  resources:\n    requests:\n      storage: 1Gi\n---\n"
          f"apiVersion: batch/v1\nkind: Job\nmetadata:\n  name: init-data\n  namespace: {ns}\nspec:\n  template:\n    spec:\n"
          f"      restartPolicy: OnFailure\n      containers:\n        - name: init\n          image: univ-is:latest\n          imagePullPolicy: IfNotPresent\n"
          f"          command: [\"python\", \"-m\", \"deploy.init_data\", \"ft\"]\n          env:\n            - {{name: DATA_DIR, value: /data}}\n"
          f"            - {{name: TOPOLOGY_SRC, value: /config/topology.json}}\n          volumeMounts:\n"
          f"            - {{name: data, mountPath: /data}}\n            - {{name: topo, mountPath: /config}}\n      volumes:\n"
          f"        - name: data\n          persistentVolumeClaim: {{claimName: data}}\n        - name: topo\n          configMap: {{name: topology}}\n")
    for svc, items in groups.items():
        app = "common.monitor" if svc == "monitor" else f"ft.{svc}"
        replicas = len(items)
        probe_ready = "/health/live" if svc == "monitor" else "/health/ready"
        y = f"""apiVersion: v1
kind: Service
metadata:
  name: {svc}
  namespace: {ns}
spec:
  clusterIP: None            # headless: stable per-pod DNS names (<pod>.{svc})
  selector: {{app: {svc}}}
  ports: [{{port: {CONTAINER_PORT}}}]
---
apiVersion: apps/v1
kind: StatefulSet
metadata:
  name: {svc}
  namespace: {ns}
spec:
  serviceName: {svc}
  replicas: {replicas}                       # service replication
  podManagementPolicy: Parallel
  updateStrategy: {{type: RollingUpdate}}    # rolling updates, one replica at a time
  selector:
    matchLabels: {{app: {svc}}}
  template:
    metadata:
      labels: {{app: {svc}}}
      annotations:                         # picked up by Prometheus' Kubernetes service discovery
        prometheus.io/scrape: "true"
        prometheus.io/port: "{CONTAINER_PORT}"
    spec:
      initContainers:                      # never start on a half-created database (init-data Job writes the marker last)
        - name: wait-for-data
          image: univ-is:latest
          imagePullPolicy: IfNotPresent
          command: ["sh", "-c", "until [ -f /data/.initialized ]; do echo waiting for init-data; sleep 1; done"]
          volumeMounts:
            - {{name: data, mountPath: /data}}
      affinity:
        podAntiAffinity:                   # replicas of one tier land on different nodes
          preferredDuringSchedulingIgnoredDuringExecution:
            - weight: 100
              podAffinityTerm:
                labelSelector: {{matchLabels: {{app: {svc}}}}}
                topologyKey: kubernetes.io/hostname
      containers:
        - name: {svc}
          image: univ-is:latest
          imagePullPolicy: IfNotPresent
          env:
            - {{name: APP, value: {app}}}
            - {{name: DATA_DIR, value: /data}}
            - {{name: TOPOLOGY_FILE, value: /config/topology.json}}
            - {{name: INSTANCE_ID, valueFrom: {{fieldRef: {{fieldPath: metadata.name}}}}}}
            - {{name: NODE, valueFrom: {{fieldRef: {{fieldPath: spec.nodeName}}}}}}
          ports: [{{containerPort: {CONTAINER_PORT}}}]
          readinessProbe:                  # health check -> removed from service endpoints when failing
            httpGet: {{path: {probe_ready}, port: {CONTAINER_PORT}}}
            periodSeconds: 2
            failureThreshold: 2
          livenessProbe:                   # self-healing: kubelet restarts a hung process
            httpGet: {{path: /health/live, port: {CONTAINER_PORT}}}
            periodSeconds: 3
            failureThreshold: 3
          resources:
            requests: {{cpu: 100m, memory: 128Mi}}
            limits: {{cpu: 500m, memory: 256Mi}}
          volumeMounts:
            - {{name: data, mountPath: /data}}
            - {{name: topo, mountPath: /config}}
      volumes:
        - name: data
          persistentVolumeClaim: {{claimName: data}}
        - name: topo
          configMap: {{name: topology}}
---
apiVersion: policy/v1
kind: PodDisruptionBudget                  # node drains / upgrades can never remove the last replica
metadata:
  name: {svc}
  namespace: {ns}
spec:
  minAvailable: {max(0, replicas - 1)}
  selector:
    matchLabels: {{app: {svc}}}
"""
        if svc == "gateway":
            y += f"""---
apiVersion: v1
kind: Service                              # load balancer in front of the two gateways (client entry point)
metadata:
  name: gateway-lb
  namespace: {ns}
spec:
  type: LoadBalancer                       # gets an external IP on a cloud; the fixed nodePort works everywhere
  selector: {{app: gateway}}
  ports: [{{port: 80, targetPort: {CONTAINER_PORT}, nodePort: {NODEPORT["gateway"]}}}]
"""
        write(os.path.join(K, f"10-{svc}.yaml"), y)
    write(os.path.join(K, "20-monitoring.yaml"), k8s_monitoring(ns))
    files = ["00-namespace.yaml", "01-config-storage.yaml"] + [f"10-{s}.yaml" for s in groups] + ["20-monitoring.yaml"]
    write(os.path.join(K, "kustomization.yaml"),
          "# kubectl apply -k deploy/k8s     (generated by deploy/generate.py)\n"
          "apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n"
          + "".join(f"  - {f}\n" for f in files))


